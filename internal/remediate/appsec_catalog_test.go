func webAsset(t string) platform.Asset {
	return platform.Asset{ID: "a1", TenantID: "t1", Type: t, Target: "https://app.example.com"}
}

// THE handoff property (ADR 0024 gap 3): the AI Pentester proves an SQLi by exploiting it, and before
// this the proposal it produced was a ticket titled "review <finding>" carrying only the finding's own
// description. The strongest evidence in the product met the weakest response.
func TestPropose_ProvenWebFindingGetsAClassCorrectFixNotAReviewTicket(t *testing.T) {
	f := types.Finding{
		ID: "f1", Tool: "sqlmap", RuleID: "sqlmap::boolean-blind", Severity: types.SeverityHigh,
		Title: "SQL injection in search parameter", CWE: []string{"CWE-89"},
		Endpoint:           "https://app.example.com/search?q=",
		VerificationStatus: types.VerificationVerified,
	}
	act, ok := Propose(f, webAsset("web_application"), ids())
	if !ok {
		t.Fatal("a proven web finding must produce an action")
	}
	if strings.HasPrefix(act.Title, "tsengine: review ") {
		t.Fatalf("an exploitation-proven finding must not fall to the generic review ticket: %s", act.Title)
	}
	if act.Payload["remediation_type"] != rtypeParameterizeQuery {
		t.Errorf("want %s, got %v", rtypeParameterizeQuery, act.Payload["remediation_type"])
	}
	rb, _ := act.Payload["remediation"].(string)
	if !strings.Contains(rb, "PARAMETERISED") {
		t.Errorf("the runbook must name the actual fix, got: %s", rb)
	}
	// Grounded (§10): the finding's own endpoint, not the asset-wide target.
	if act.Payload["target"] != "https://app.example.com/search?q=" {
		t.Errorf("target must be the finding's own endpoint, got %v", act.Payload["target"])
	}
}

// A container CVE has a MECHANICAL fix and the scanner already reports the version. Citing it is the
// difference between a fix and a chore.
func TestPropose_ContainerCVECitesTheScannerReportedFixedVersion(t *testing.T) {
	f := types.Finding{
		ID: "f2", Tool: "grype", RuleID: "grype::CVE-2024-1234", Severity: types.SeverityHigh,
		Title:    "CVE-2024-1234 in libfoo",
		ToolArgs: map[string]string{"pkg": "libfoo", "installed_version": "1.2.3", "fixed_version": "1.2.9"},
	}
	act, _ := Propose(f, webAsset("container_image"), ids())
	if act.Payload["remediation_type"] != rtypePackageUpgrade {
		t.Fatalf("want %s, got %v", rtypePackageUpgrade, act.Payload["remediation_type"])
	}
	rb, _ := act.Payload["remediation"].(string)
	for _, want := range []string{"libfoo", "1.2.9", "1.2.3"} {
		if !strings.Contains(rb, want) {
			t.Errorf("runbook must cite the real coordinate %q, got: %s", want, rb)
		}
	}
}

// The refusal that makes the citation trustworthy: with no fixed version reported, the runbook must
// SAY so. An upgrade target we invented is worse than none, because it is actionable and wrong.
func TestPropose_ContainerCVEWithNoFixedVersionNeverInventsOne(t *testing.T) {
	f := types.Finding{
		ID: "f3", Tool: "trivy", RuleID: "trivy::CVE-2024-9999", Severity: types.SeverityHigh,
		Title:    "CVE-2024-9999 in openssl (debian base layer)",
		ToolArgs: map[string]string{"pkg": "openssl", "installed_version": "3.0.11"},
	}
	act, _ := Propose(f, webAsset("container_image"), ids())
	if act.Payload["remediation_type"] != rtypeBaseImageUpgrade {
		t.Fatalf("want %s, got %v", rtypeBaseImageUpgrade, act.Payload["remediation_type"])
	}
	rb, _ := act.Payload["remediation"].(string)
	if !strings.Contains(rb, "did not report a fixed version") {
		t.Errorf("must state that no fixed version was reported, got: %s", rb)
	}
	if strings.Contains(rb, "or later") {
		t.Errorf("must not render an upgrade target it does not have, got: %s", rb)
	}
}

// An unmatched finding must keep the generic ticket. A catalog that guesses is worse than one that
// declines: a confident wrong fix costs more than an honest "review this".
func TestPropose_UnmatchedAppsecFindingKeepsTheGenericTicket(t *testing.T) {
	f := types.Finding{ID: "f4", Tool: "nuclei", RuleID: "nuclei::some-novel-thing",
		Title: "An unclassified observation", Severity: types.SeverityLow}
	act, ok := Propose(f, webAsset("api"), ids())
	if !ok {
		t.Fatal("must still produce an action")
	}
	if _, has := act.Payload["remediation_type"]; has {
		t.Errorf("an unmatched finding must not be labelled with a class: %v", act.Payload)
	}
	if !strings.HasPrefix(act.Title, "tsengine: review ") {
		t.Errorf("want the generic review ticket, got %s", act.Title)
	}
}

