// CLASS-LEVEL: every catalog entry must be REACHABLE. A matcher no finding can trip is dead code that
// reads as coverage — the same vacuous-pass shape §14.2 rule 6 forbids in a guard. This table also
// pins the most-specific-first ordering: if a broad class starts shadowing a narrow one, the narrow
// one's row fails here rather than silently degrading a customer's fix.
func TestAppsecCatalog_EveryClassIsReachableAndNamedUniquely(t *testing.T) {
	cases := []struct {
		want string
		f    types.Finding
	}{
		{rtypePackageUpgrade, types.Finding{Tool: "grype", Title: "CVE-2024-1 in libx", ToolArgs: map[string]string{"pkg": "libx", "fixed_version": "2.0"}}},
		{rtypeBaseImageUpgrade, types.Finding{Tool: "trivy", Title: "CVE-2024-2 in alpine base image layer"}},
		{rtypeContainerHardening, types.Finding{Tool: "dockle", Title: "CIS-DI-0001: image runs as root user"}},
		{rtypeImageSigning, types.Finding{Tool: "cosign", Title: "unsigned image digest in registry"}},
		{rtypeParameterizeQuery, types.Finding{Title: "SQL injection", CWE: []string{"CWE-89"}}},
		{rtypeEncodeOutput, types.Finding{Title: "reflected cross-site scripting", CWE: []string{"CWE-79"}}},
		{rtypeSSRFAllowlist, types.Finding{Title: "server-side request forgery", CWE: []string{"CWE-918"}}},
		{rtypeRedirectAllowlist, types.Finding{Title: "open redirect", CWE: []string{"CWE-601"}}},
		{rtypePathCanonicalize, types.Finding{Title: "path traversal", CWE: []string{"CWE-22"}}},
		{rtypeAvoidShellExec, types.Finding{Title: "command injection", CWE: []string{"CWE-78"}}},
		{rtypeEnforceObjectAuthz, types.Finding{Title: "BOLA on /orders/{id}", CWE: []string{"CWE-639"}}},
		{rtypeRotateDefaultCreds, types.Finding{Title: "default login admin:admin", CWE: []string{"CWE-798"}}},
		{rtypeRemoveExposedFile, types.Finding{Title: "exposed .env file", CWE: []string{"CWE-200"}}},
		{rtypeGraphQLIntrospect, types.Finding{Tool: "inql", Title: "GraphQL introspection enabled"}},
		{rtypeTLSHardening, types.Finding{Title: "weak cipher / TLS 1.0 supported", CWE: []string{"CWE-327"}}},
		{rtypeSecurityHeaders, types.Finding{Title: "missing Content-Security-Policy", CWE: []string{"CWE-693"}}},
	}
	reached := map[string]bool{}
	for _, c := range cases {
		got, rb, ok := appsecFixCatalog(c.f)
		if !ok || got != c.want {
			t.Errorf("finding %q: want class %s, got %s (matched=%v)", c.f.Title, c.want, got, ok)
			continue
		}
		if strings.TrimSpace(rb) == "" {
			t.Errorf("class %s produced an empty runbook", got)
		}
		reached[got] = true
	}
	// Every class declared in the catalog must appear above — a class with no representative case is
	// one nobody has shown can fire.
	for _, m := range appsecCatalog {
		if !reached[m.rtype] {
			t.Errorf("catalog class %s is unreachable by any representative finding (dead coverage)", m.rtype)
		}
	}
	seen := map[string]bool{}
	for _, m := range appsecCatalog {
		if seen[m.rtype] {
			t.Errorf("duplicate remediation_type %s: two classes cannot share a machine-readable name", m.rtype)
		}
		seen[m.rtype] = true
	}
	if len(appsecRunbookRemediations) != len(appsecCatalog) {
		t.Errorf("the runbook-routing set must derive from the catalog: %d vs %d", len(appsecRunbookRemediations), len(appsecCatalog))
	}
}

// The three surfaces that had no fix path must now all reach the catalog.
func TestPropose_AllThreeAppsecSurfacesReachTheCatalog(t *testing.T) {
	f := types.Finding{ID: "f6", Title: "reflected cross-site scripting", CWE: []string{"CWE-79"}, Endpoint: "https://x/y"}
	for _, at := range []string{"web_application", "api", "container_image"} {
		act, ok := Propose(f, webAsset(at), ids())
		if !ok || act.Payload["remediation_type"] != rtypeEncodeOutput {
			t.Errorf("%s: want %s, got %v (ok=%v)", at, rtypeEncodeOutput, act.Payload["remediation_type"], ok)
		}
	}
}
